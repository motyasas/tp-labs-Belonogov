namespace BankSystem.Core;

/// <summary>
/// Контракт "журнал операций банка".
/// Банк знает только этот интерфейс и не знает, КУДА на самом деле пишутся записи:
/// в файл, в память или куда-то ещё. Нужную реализацию передают банку в конструктор
/// (это и есть "внедрение зависимости").
/// </summary>
public interface ITransactionLog
{
    /// <summary>Добавить запись в журнал.</summary>
    void Write(string record);

    /// <summary>Получить все записи журнала (в порядке добавления).</summary>
    List<string> ReadAll();
}
